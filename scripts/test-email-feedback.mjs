import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync('public/assets/story.js','utf8');
const ensure=source.slice(source.indexOf('async function ensureAccount('),source.indexOf('async function cloudRequest('));
let prompts=0,logins=0,writes=0;
const auth={ready:true,userId:'user-a',emailVerified:false,signIn:()=>logins++};
const context=vm.createContext({window:{storyforgeAuth:auth},showEmailVerification:()=>prompts++,save:()=>writes++,sessionStorage:{setItem:()=>writes++},toast(){}});
vm.runInContext(ensure,context);
assert.equal(await vm.runInContext("ensureAccount('publish')",context),false);
assert.equal(prompts,1);assert.equal(logins,0);assert.equal(writes,0);
auth.emailVerified=true;
assert.equal(await vm.runInContext("ensureAccount('save-story')",context),true);
auth.userId=null;
assert.equal(await vm.runInContext("ensureAccount('save-story')",context),false);assert.equal(logins,1);
const modalCode=source.slice(source.indexOf('function showEmailVerification(){'),source.indexOf('function showAccountRequired(){'));
let opened=0,removed=0,focused=0,appended=0;
const buttons={};const modal={querySelector:id=>buttons[id]??=( {focus:()=>focused++} ),remove:()=>removed++};
const modalContext=vm.createContext({document:{getElementById:()=>null,createElement:()=>modal,body:{append:()=>appended++}},window:{storyforgeAuth:{verifyEmail:()=>opened++}}});
vm.runInContext(modalCode+'showEmailVerification()',modalContext);
assert.match(modal.innerHTML,/Verify your email/);assert.equal(appended,1);assert.equal(focused,1);
buttons['#verify-email-action'].onclick();assert.equal(opened,1);assert.equal(removed,1);
console.log('PASS: unverified feedback, account-settings action and verified-user recovery');
